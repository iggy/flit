// Package auth holds flit's API token and enforces it on every RPC.
package auth

import (
	"crypto/rand"
	"encoding/base64"
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// TokenFile is the token's file name inside the data directory.
const TokenFile = "token"

const tokenPrefix = "flit_"

// NewToken returns a fresh random token.
func NewToken() string {
	b := make([]byte, 32)
	_, _ = rand.Read(b) // crypto/rand.Read never returns an error.
	return tokenPrefix + base64.RawURLEncoding.EncodeToString(b)
}

// LoadOrCreateToken returns the token stored in dataDir, generating and
// storing a new one if there is none. created reports whether it was
// generated by this call (i.e. this is flit's first run with this data dir).
func LoadOrCreateToken(dataDir string) (token string, created bool, err error) {
	path := filepath.Join(dataDir, TokenFile)
	token, err = ReadToken(dataDir)
	if err == nil {
		return token, false, nil
	}
	if !errors.Is(err, os.ErrNotExist) {
		return "", false, err
	}

	token = NewToken()
	f, err := os.OpenFile(path, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0o600)
	if errors.Is(err, os.ErrExist) {
		// Lost a race with another process; use its token.
		token, err = ReadToken(dataDir)
		return token, false, err
	}
	if err != nil {
		return "", false, err
	}
	if _, err := f.WriteString(token + "\n"); err != nil {
		f.Close()
		return "", false, err
	}
	if err := f.Close(); err != nil {
		return "", false, err
	}
	return token, true, nil
}

// ReadToken returns the token stored in dataDir.
func ReadToken(dataDir string) (string, error) {
	path := filepath.Join(dataDir, TokenFile)
	b, err := os.ReadFile(path)
	if err != nil {
		return "", err
	}
	token := strings.TrimSpace(string(b))
	if token == "" {
		return "", fmt.Errorf("%s is empty; delete it to generate a new token", path)
	}
	return token, nil
}
